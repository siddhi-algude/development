const REFRESH_COOKIE_NAME = "insta_refresh";

const setRefreshCookie = (res: Response, refreshToken: string) => {
  const isProd = env.nodeEnv === "production";
  res.cookie(REFRESH_COOKIE_NAME, refreshToken, {
    httpOnly: true,
    secure: isProd,
    sameSite: "lax",
    maxAge: env.jwtRefreshExpiresInDays * 24 * 60 * 60 * 1000,
    path: "/api/auth",
  });
};

const clearRefreshCookie = (res: Response) => {
  res.clearCookie(REFRESH_COOKIE_NAME, {
    path: "/api/auth",
  });
};

export const registerHandler = async (req: Request, res: Response) => {
  try {
    const { email, username, password } = req.body;
    const result = await register({ email, username, password });

    // we need refresh token generated by service → for now, we’ll generate a session separately
    // Easiest: call login after register. But we already did that in service.
    // To set cookie, we need refresh token, so we slightly adjust: call refreshSession with cookie later.
    // For simplicity: return only accessToken here and let frontend log in again.
    // --- To keep it clean, let's just *not* auto-login on register:
    //  -> In real production, you either auto-login OR ask them to confirm email first.
    return res.status(201).json({
      user: result.user,
      tokens: result.tokens,
      // refresh token is inside cookie (we'll inject later when we adjust service to return it too)
    });
  } catch (err: any) {
    return res.status(400).json({ message: err.message || "Registration failed" });
  }
};

export const loginHandler = async (req: Request, res: Response) => {
  try {
    const { emailOrUsername, password } = req.body;
    const authResponse = await login({ emailOrUsername, password });

    // Right now authResponse doesn't expose refresh token.
    // To make refresh token available here, in a "real" implementation
    // we would return it from `createSessionForUser`, but keep it internal.
    // For this explanation, let's simulate it by just calling `refreshSession` from cookie path.
    // For clarity & correctness, we actually need `createSessionForUser` to also give refreshToken.

    // SMALL ADJUSTMENT: we’ll modify createSessionForUser to return refreshToken as well.
    // (See below after we adjust the service.)

    // So assume authResponse.tokens.refreshToken exists now:

    // @ts-ignore - we'll add refreshToken soon
    const refreshToken = authResponse.tokens.refreshToken;
    setRefreshCookie(res, refreshToken);

    return res.json({
      user: authResponse.user,
      tokens: {
        accessToken: authResponse.tokens.accessToken,
      },
    });
  } catch (err: any) {
    return res.status(401).json({ message: err.message || "Login failed" });
  }
};

export const refreshHandler = async (req: Request, res: Response) => {
  try {
    const refreshToken = req.cookies[REFRESH_COOKIE_NAME];
    if (!refreshToken) {
      return res.status(401).json({ message: "No refresh token" });
    }

    const authResponse = await refreshSession(refreshToken);

    // @ts-ignore - will exist after adjustment
    const newRefreshToken = authResponse.tokens.refreshToken;
    setRefreshCookie(res, newRefreshToken);

    return res.json({
      user: authResponse.user,
      tokens: {
        accessToken: authResponse.tokens.accessToken,
      },
    });
  } catch (err: any) {
    clearRefreshCookie(res);
    return res.status(401).json({ message: err.message || "Refresh failed" });
  }
};

